// Build a family's clip library from its recipes and the source cache, then refresh CREDITS.md.
// Usage: bun run anim:build <family> [--only id,id]
import { $ } from "bun";
import { mkdtemp, readdir, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { FAMILIES, readSources } from "./cache";

const BUILDERS: Record<string, string> = { biped: "scripts/rig/library.py" };

const { values, positionals } = parseArgs({ allowPositionals: true, options: { only: { type: "string" } } });
const family = positionals[0];
if (!family || !BUILDERS[family]) throw new Error(`Usage: bun run anim:build <${Object.keys(BUILDERS).join("|")}> [--only id,id]`);
const blender = process.env.BLENDER ?? "/Applications/Blender.app/Contents/MacOS/Blender";
const work = await mkdtemp(join(tmpdir(), `anim-${family}-`));
const dest = join(FAMILIES, family);

const only = values.only ? ["--only", values.only] : [];
const log = await $`${blender} -b --factory-startup -P ${BUILDERS[family]} -- ${work} ${only}`.nothrow().quiet();
const out = log.stdout.toString();
for (const line of out.split("\n")) if (/^(BUILT|LIBRARY)/.test(line)) console.log(line);
if (log.exitCode !== 0 || !out.includes("LIBRARY")) {
  console.error(out.split("\n").filter((l) => /Error|Traceback|line \d+|Exception/.test(l)).join("\n"));
  process.exit(1);
}

// --only rebuilds just those clips: merge them into the existing catalog and sets
type Entry = { id: string; set: string; source: string };
const built: Entry[] = await Bun.file(join(work, "catalog.json")).json();
const catalogPath = join(dest, "catalog.json");
const previous: Entry[] = values.only && (await Bun.file(catalogPath).exists()) ? await Bun.file(catalogPath).json() : [];
if (values.only && previous.length) throw new Error("--only can't merge into existing set files yet; run a full build");

await mkdir(join(dest, "clips"), { recursive: true });
if (!values.only) await rm(join(dest, "clips"), { recursive: true, force: true }).then(() => mkdir(join(dest, "clips")));
for (const f of await readdir(work)) {
  if (!f.endsWith(".glb")) continue;
  const to = f === "reference.glb" ? join(dest, f) : join(dest, "clips", f);
  const tex = f === "reference.glb" ? ["--texture-compress", "webp", "--texture-size", "1024"] : [];
  await $`bunx gltf-transform optimize ${join(work, f)} ${to} --compress meshopt ${tex}`.quiet();
}
await Bun.write(catalogPath, JSON.stringify(built, null, 2) + "\n");

// CREDITS.md covers every source any family's catalog uses
const lines = ["# Animation credits", "", "Generated by `bun run anim:build`. Sources whose licence asks for credit, and every source used:", ""];
for (const fam of (await readdir(FAMILIES, { withFileTypes: true })).filter((d) => d.isDirectory() && d.name !== "families")) {
  const cat = Bun.file(join(FAMILIES, fam.name, "catalog.json"));
  if (!(await cat.exists())) continue;
  const used = new Set(((await cat.json()) as Entry[]).map((e) => e.source));
  for (const s of (await readSources(fam.name)).filter((x) => used.has(x.id)))
    lines.push(`- **${s.name}** (${fam.name}): ${s.license}. ${s.credit ?? "No credit required."} <${s.url}>`);
}
await Bun.write(join(FAMILIES, "CREDITS.md"), lines.join("\n") + "\n");

const sizes = await $`du -sh ${join(dest, "clips")} ${join(dest, "reference.glb")}`.text();
console.log(`${family}: ${built.length} clips\n${sizes.trim()}`);
